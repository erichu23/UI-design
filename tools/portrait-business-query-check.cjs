const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..'),read=file=>fs.readFileSync(path.join(root,file),'utf8');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'chrome'});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
    page.setDefaultTimeout(10000);
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('https://portrait.test/**',route=>{
      const pathname=new URL(route.request().url()).pathname;
      if(pathname.startsWith('/assets/icons/lucide/'))return route.fulfill({contentType:'image/svg+xml',body:read(pathname.slice(1))});
      return route.fulfill({contentType:'text/html',body:read('fragments/bank-analysis.html').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'').replace(/<link\b[^>]*>/gi,'')});
    });
    await page.goto('https://portrait.test/');
    for(const file of ['assets/css/base.css','assets/css/pages/bank-analysis.css','assets/css/pages/portrait.css','assets/css/pages/portrait-business-query.css'])await page.addStyleTag({content:read(file).replaceAll('../../icons/lucide/','https://portrait.test/assets/icons/lucide/')});
    await page.addStyleTag({content:'#wpModal,.tab-container{display:none!important} html,body{overflow:auto!important;height:auto!important} #pane-biz{display:block!important;height:auto!important;overflow:visible!important}'});
    await page.evaluate(()=>{
      document.querySelectorAll('.tab-pane').forEach(pane=>{pane.hidden=pane.id!=='pane-biz';pane.classList.toggle('hide',pane.hidden);});
      document.querySelectorAll('#topTabs .tab').forEach(tab=>tab.classList.toggle('active',tab.dataset.top==='biz'));
      // Accelerate only the existing 12-second demo fetch, without changing UI logic.
      const timeout=window.setTimeout;window.setTimeout=(fn,ms,...args)=>{
        if(ms===12000){window.finishBusinessQuery=()=>fn(...args);return 0;}
        return timeout(fn,ms,...args);
      };
    });
    for(const file of ['assets/js/pages/portrait-business-query.js','assets/js/pages/portrait.js'])await page.addScriptTag({content:read(file)});
    await page.evaluate(()=>document.dispatchEvent(new Event('DOMContentLoaded')));
    const firstCheck=page.locator('#portraitCounterpartyBody [data-portrait-select]').first();
    assert.equal(await page.locator('#portraitSelectionNote').textContent(),'不勾选即默认基于全部记录导出');
    const selectedName=await firstCheck.getAttribute('data-portrait-select');
    await firstCheck.check();
    assert.equal(await page.locator('#portraitSelectionNote').textContent(),'当前已选 1 家');
    assert.equal(await page.locator('.portrait-table-meta > #portraitSelectionNote').count(),1);
    const checkAlignment=await page.evaluate(()=>{
      const head=document.querySelector('[data-portrait-select-all]').getBoundingClientRect();
      const row=document.querySelector('[data-portrait-select]').getBoundingClientRect();
      return Math.abs(head.left+head.width/2-row.left-row.width/2);
    });
    assert(checkAlignment<1,'header and row checkboxes have the same horizontal center');
    assert.equal(await page.locator('#portraitCounterpartyHead [data-portrait-select-all]').evaluate(input=>input.indeterminate),true);
    await page.locator('#portraitBusinessRefresh').click();
    const dialog=page.locator('.portrait-business-dialog');
    assert.equal(await page.locator('.portrait-business-sync > #portraitBusinessRefreshState').count(),1);
    assert.equal(await dialog.isVisible(),true);
    assert.equal(await dialog.locator('h2').textContent(),'导出包含交易信息和工商信息的对手方清单');
    assert.equal(await dialog.locator('header [data-query-edit]').count(),0);
    assert.equal(await dialog.locator('.pbq-editbar [data-query-edit]').isVisible(),true);
    assert.equal(await dialog.locator('header [type=submit]').isVisible(),true);
    await dialog.locator('[data-condition-top="0"]').fill('2');
    await dialog.locator('[data-condition-top="1"]').fill('2');
    await dialog.locator('[data-query-add]').click();
    assert.equal(await dialog.locator('.pbq-condition').count(),3);
    await dialog.locator('[data-condition-remove="2"]').click();
    await dialog.locator('[name=people]').check();
    await dialog.locator('[name=shareholders]').check();
    assert.equal(await dialog.locator('[name=shareholdersDepth]').isVisible(),true);
    await dialog.locator('[name=lawsuit]').check();
    await dialog.locator('[type=submit]').click();
    assert.equal(await dialog.getAttribute('aria-busy'),'true');
    assert.equal(await dialog.locator('[type=submit]').textContent(),'正在查询…');
    assert.equal(await dialog.locator('[type=submit]').isDisabled(),true);
    assert.equal(await dialog.locator('.pbq-close').isEnabled(),true);
    await dialog.locator('.pbq-close').click();
    assert.equal(await dialog.isVisible(),false);
    assert.equal(await page.locator('#portraitBusinessRefresh [data-query-entry-label]').textContent(),'工商信息查询中');
    await page.locator('#portraitCustomBusinessQuery').click();
    assert.equal(await dialog.getAttribute('aria-busy'),'false');
    await page.evaluate(()=>window.finishBusinessQuery());
    assert.equal(await dialog.locator('h2').textContent(),'导出特定企业列表的工商信息清单');
    await page.keyboard.press('Escape');
    await page.locator('#portraitBusinessRefresh').click();
    await dialog.locator('[data-query-download]').waitFor({state:'visible'});
    assert.equal(await dialog.getAttribute('aria-busy'),'false');
    assert.equal(await dialog.locator('.pbq-query-indicator.is-ready').textContent(),'查询完成，可导出报告');
    assert((await page.locator('#portraitBusinessRefreshState').textContent()).includes('本表更新'));
    assert((await dialog.locator('.pbq-status').textContent()).includes('已匹配 4 家'));
    assert.equal(await dialog.locator('.pbq-results').count(),0);
    assert.equal(await page.locator('#portraitCounterpartyBody [data-portrait-select]').first().isChecked(),true,'selection survives query result redraw');
    assert.equal(await page.locator('#portraitCounterpartyBody tr').first().locator('.portrait-dishonest-cell.portrait-business-pending,.portrait-lawsuit-cell.portrait-business-pending').count(),0,'queried risk cells must not remain masked');
    await page.screenshot({path:'/private/tmp/portrait-business-current.png'});
    const filePromise=page.waitForEvent('download');await dialog.locator('[data-query-download]').click();
    assert((await filePromise).suggestedFilename().includes('对手方交易及工商信息'));
    await dialog.locator('[data-query-edit]').click();
    assert.equal(await dialog.locator('[data-condition-top="0"]').isEnabled(),true);
    await page.keyboard.press('Escape');
    assert.equal(await dialog.isVisible(),false);
    assert.equal(await page.locator('#portraitBusinessRefresh [data-query-entry-label]').textContent(),'查看对手方工商信息');
    assert.equal(await page.locator('#portraitBusinessRefresh [data-query-entry-updated]').isVisible(),true);
    assert((await page.locator('#portraitBusinessRefresh [data-query-entry-updated]').textContent()).startsWith('最新更新：'));
    assert.equal(await page.locator('#portraitBusinessRefreshState').isVisible(),false);
    assert.equal(await page.locator('#portraitBusinessRefresh').evaluate(node=>document.activeElement===node),true);
    const toolbar=await page.locator('.portrait-business-sync').evaluate(node=>{
      const buttons=[...node.querySelectorAll('button')].map(button=>button.getBoundingClientRect());
      return {height:node.getBoundingClientRect().height,aligned:buttons.every(rect=>Math.abs(rect.top-buttons[0].top)<2)};
    });
    assert(toolbar.height<=29&&toolbar.aligned,'query buttons and update time stay on one compact line');
    await page.locator('.portrait-table-viewbar').first().screenshot({path:'/private/tmp/portrait-query-toolbar.png'});
    const resultDownload=page.waitForEvent('download');
    await page.locator('#portraitGenerateResult').click();
    const resultFile=await resultDownload,resultCsv=fs.readFileSync(await resultFile.path(),'utf8');
    assert.equal(resultCsv.trim().split('\n').length,2);
    assert(resultCsv.includes(selectedName));
    const flowDownload=page.waitForEvent('download');
    await page.locator('#portraitExportBtn').click();
    const flowFile=await flowDownload,flowCsv=fs.readFileSync(await flowFile.path(),'utf8');
    assert(flowFile.suggestedFilename().includes('流水明细'));
    assert(flowCsv.trim().split('\n').slice(1).every(line=>line.split(',')[2]==='"'+selectedName+'"'));
    await page.locator('#portraitCustomBusinessQuery').click();
    const mainQueryState=await page.locator('#portraitBusinessRefreshState').textContent();
    assert.equal(await dialog.locator('h2').textContent(),'导出特定企业列表的工商信息清单');
    await dialog.locator('[type=submit]').click();
    assert((await dialog.locator('.pbq-error').textContent()).includes('请先上传'));
    const names=await page.locator('#portraitCounterpartyBody tr td.portrait-fixed-col-1').allTextContents();
    const csv='公司名称,标签1,标签2,标签3\n'+names[0]+',测试A,,\n'+names[0]+',重复,,\n未匹配测试企业,测试B,,\n';
    await dialog.locator('[type=file]').setInputFiles({name:'企业名单.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
    await page.waitForFunction(()=>document.querySelector('.pbq-file-state').textContent.includes('已去重 1 家'));
    assert((await dialog.locator('.pbq-file-state').textContent()).includes('已去重 1 家'));
    assert.equal(await dialog.locator('.pbq-list-wrap tbody tr').count(),2);
    await dialog.locator('[type=submit]').click();
    await dialog.locator('[data-query-download]').waitFor({state:'visible'});
    assert.equal(await dialog.locator('.pbq-list-wrap tbody tr').count(),2);
    assert((await dialog.locator('.pbq-status').textContent()).includes('待查询 1 家'));
    assert.equal(await page.locator('#portraitCustomBusinessQuery [data-query-entry-label]').textContent(),'查看自定义企业工商信息');
    assert.equal(await dialog.locator('.pbq-query-indicator.is-partial').textContent(),'查询结束，可导出已获取结果');
    assert.equal(await page.locator('#portraitBusinessRefreshState').textContent(),mainQueryState,'custom list query must not change current-table update time');
    const rowsBefore=await page.locator('#portraitCounterpartyBody tr td.portrait-fixed-col-1').allTextContents();
    assert(!rowsBefore.includes('未匹配测试企业'));
    await page.screenshot({path:'/private/tmp/portrait-business-custom.png'});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await dialog.evaluate(node=>node.scrollWidth<=node.clientWidth+1),true);
    assert.equal(await dialog.locator('main').evaluate(node=>node.scrollWidth<=node.clientWidth+1),true);
    await page.screenshot({path:'/private/tmp/portrait-business-mobile.png'});
    await page.keyboard.press('Escape');
    await page.setViewportSize({width:1440,height:1000});
    await page.locator('#portraitFlowInflow').click();
    assert.equal(await page.locator('#portraitFlowInflow').getAttribute('aria-selected'),'true');
    assert.deepEqual(errors,[]);
    console.log('PASS: ranking union, optional query fields, editing, current table enrichment, CSV import/deduplication, custom results, downloads, Escape/focus, mobile overflow and unchanged flow tabs.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
