const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const values=new Map();
const context={window:{},localStorage:{getItem:key=>values.get(key)||null,setItem:(key,value)=>values.set(key,value)}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(root,'assets/js/config/routine-demo-data.js'),'utf8'),context);
const html=fs.readFileSync(path.join(root,'fragments/fund-flow-check.html'),'utf8');
const start=html.indexOf('const checkMeta = {');
const end=html.indexOf('const RISK_ROUTINE_STATE_KEY',start);
vm.runInContext(html.slice(start,end)+'\nwindow.metadata=checkMeta;',context);
const demo=context.window.RoutineDemoData;
const parameters=context.window.metadata;
Object.entries(demo.amountDefaults).forEach(([id,defaults])=>Object.entries(defaults).forEach(([key,value])=>{
  assert.equal(parameters[id].filters.find(filter=>filter.key===key).defaultVal,value,`${id}/${key} default agrees with the demo`);
}));
assert.equal(parameters['1.1'].filters[0].defaultVal,50000);
const data=demo.create({parameters});
assert.equal(data.counterparties.length,144);
assert(data.transactions.length>1500);
assert.equal(new Set(data.counterparties.map(row=>row.name)).size,144);
assert.equal(demo.ids.length,22);
assert.equal(JSON.stringify(data),JSON.stringify(demo.create({parameters})),'demo should be deterministic');
const summaries=demo.summarize(data);
assert(summaries.every(row=>row.counterparties>0&&row.transactions>0&&row.amount>0),'all 22 routines have real matching examples');
const byId=new Map(data.counterparties.map(row=>[row.id,row]));
assert.equal(new Set(data.transactions.map(row=>row.txId)).size,data.transactions.length);
data.transactions.forEach(tx=>{
  assert(byId.has(tx.cpId));assert(tx.amount>0);assert(tx.date>='2024-01-01'&&tx.date<='2025-12-31');
  assert(tx.balance>=0);assert.equal(tx.flags.length,tx.checkIds.length);
});
data.counterparties.forEach(cp=>{
  const transactions=data.transactions.filter(row=>row.cpId===cp.id);
  assert.equal(cp.txCount,transactions.length);
  const inflow=transactions.filter(row=>row.dir==='流入').reduce((sum,row)=>sum+Math.round(row.amount*100),0);
  const outflow=transactions.filter(row=>row.dir==='流出').reduce((sum,row)=>sum+Math.round(row.amount*100),0);
  assert.equal(cp.inflowCents,inflow);assert.equal(cp.outflowCents,outflow);
  assert.equal(cp.inflow,inflow/1000000);assert.equal(cp.outflow,outflow/1000000);
  const hits=new Set(transactions.flatMap(row=>Array.from(row.flags)));
  assert.deepEqual(Array.from(cp.hits).sort(),Array.from(hits).sort(),'summary hits are the union of transaction hits');
});
summaries.forEach(summary=>{
  const matching=data.transactions.filter(row=>row.checkIds.includes(summary.id));
  assert.equal(summary.counterparties,new Set(matching.map(row=>row.cpId)).size);
  assert.equal(summary.transactions,matching.length);
  assert.equal(summary.amount,matching.reduce((sum,row)=>sum+Math.round(row.amount*100),0)/100);
});
const first=data.transactions.find(row=>row.checkIds.includes('3.2'));
const removed=data.transactions.filter(row=>row.cpId===first.cpId&&row.checkIds.includes('3.2'));
const before=summaries.find(row=>row.id==='3.2');
const after=demo.summarize(data,{[`${first.cpId}_3.2`]:{reason:'已核实'}}).find(row=>row.id==='3.2');
assert.equal(after.counterparties,before.counterparties-1);
assert.equal(after.transactions,before.transactions-removed.length);
assert.equal(Math.round(after.amount*100),Math.round(before.amount*100)-removed.reduce((sum,row)=>sum+Math.round(row.amount*100),0));
assert(data.counterparties.some(row=>row.hits.length===0),'normal counterparts remain as a control group');
assert(data.transactions.some(row=>row.cp==='')&&data.transactions.some(row=>row.remark===''));
const strict=JSON.parse(JSON.stringify(parameters));
strict['1.1'].filters[0].defaultVal=1e12;
demo.evaluate(data,strict);
assert.equal(demo.summarize(data).find(row=>row.id==='1.1').transactions,0,'restrictive filters may legitimately yield zero');
demo.evaluate(data,parameters);
assert.deepEqual(JSON.parse(JSON.stringify(demo.summarize(data))),JSON.parse(JSON.stringify(summaries)));
values.set(demo.resultKey,JSON.stringify({version:demo.version,rows:summaries}));
assert.equal(JSON.stringify(demo.readSummary()),JSON.stringify(summaries));
values.delete(demo.resultKey);
values.set('auditCompass.specialTransactionRoutineState',JSON.stringify({routines:[{id:'1.2',filters:[{key:'totalInflow',value:null},{key:'totalOutflow',value:null}]}]}));
assert.equal(JSON.stringify(demo.readSummary()),JSON.stringify(demo.summarize(demo.create())),'legacy empty amounts use the new defaults');
values.set('auditCompass.specialTransactionRoutineState',JSON.stringify({amountDefaultsVersion:1,routines:[{id:'1.1',filters:[{key:'minAmt',value:1e12}]}]}));
assert.equal(demo.readSummary().find(row=>row.id==='1.1').transactions,0,'saved custom thresholds stay intact');
values.clear();
demo.saveParameters([{id:'1.1',filters:[{key:'minAmt',value:1e12}]}]);
assert.equal(demo.readParameters()['1.1'].filters[0].defaultVal,1e12);
assert.equal(demo.readSummary().find(row=>row.id==='1.1').transactions,0);
demo.saveParameters([{id:'1.1',filters:[{key:'minAmt',value:''}]}]);
assert.equal(demo.readParameters()['1.1'].filters[0].defaultVal,null,'intentional blank survives reads');
assert.throws(()=>demo.saveParameters([{id:'3.2',filters:[{key:'bsDate',value:'02/30'}]}]));
assert.throws(()=>demo.saveParameters([{id:'1.1',filters:[{key:'minAmt',value:-1}]}]));
assert.throws(()=>demo.saveParameters([{id:'3.8',filters:[{key:'txCountMin',value:9}]}]));
console.log(`PASS: ${data.counterparties.length} counterparties, ${data.transactions.length} transactions, all 22 routines covered; aggregates, amounts, hit unions, clear/restore, parameter changes and shared snapshots agree.`);
